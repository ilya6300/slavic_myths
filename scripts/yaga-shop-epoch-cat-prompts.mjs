export function buildEpochCatPrompt(skinId, pose) {
  const sub = SUBJECT[skinId];
  if (!sub) throw new Error(`Unknown skin ${skinId}`);
  const body = pose === 'sid' ? sub.sid : sub.sleep;
  const poseBlock = pose === 'sid' ? POSE_SID : POSE_SLEEP;
  const extraNeg =
    skinId === 'wondrous_div'
      ? NEGATIVE_WONDROUS_DIV
      : skinId === 'stormy_perun'
        ? NEGATIVE_STORMY_PERUN
        : skinId === 'fluffy_veles'
          ? NEGATIVE_FLUFFY_VELES
          : '';
  const styleBlock =
    skinId === 'stormy_perun'
      ? STYLE_BLOCK.replace(
          'Матовая шерсть, следы лепки',
          'Тело из мягкой молнии и светящихся дуг (не мех), объём как у пластилиновой скульптуры, следы лепки на световых формах',
        )
      : STYLE_BLOCK;
  return `${body}\n${poseBlock}\n${styleBlock}\n${NEGATIVE}${extraNeg}`;
}
